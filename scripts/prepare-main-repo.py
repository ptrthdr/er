#!/usr/bin/env python3
"""Prepare a source-only integration tree. No Git operations or network calls."""
import hashlib
import json
import re
import shutil
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'deliverables' / 'main-repo'
EXCLUDED = {'target', 'node_modules', 'dist', '.git', '.idea', '.vscode', '__pycache__'}

def allowed(path):
    rel = path.relative_to(ROOT)
    return (path.is_file() and not path.is_symlink()
            and not any(part in EXCLUDED for part in rel.parts)
            and not path.name.startswith('.env') and path.name != 'judge0.conf'
            and path.suffix not in {'.log', '.pyc', '.class', '.jar', '.iso'})

selected = []
for folder in ['runner', 'infra', 'docs', 'examples/integration', 'examples/palindrome']:
    selected.extend(p for p in (ROOT / folder).rglob('*') if allowed(p))
selected.extend(ROOT / p for p in [
    '.gitignore', 'Dla BACKENDOWCA.md', '.github/workflows/execution-ci.yml',
    'components/code-editor/package.json', 'components/code-editor/package-lock.json',
    'components/code-editor/src/execution-editor.js', 'components/code-editor/src/style.css',
    'scripts/prepare-local.py', 'scripts/prepare-main-repo.py', 'scripts/verify-integration.py',
    'scripts/verify-languages.py', 'scripts/verify-async.py',
    'scripts/verify-contract.py', 'scripts/validate-contract.py', 'scripts/runner_contract.py', 'scripts/verify-source-files.py', 'scripts/contract-requirements.txt'])
# This exact directory is generated by this script; never remove another checkout.
if OUTPUT.exists():
    shutil.rmtree(OUTPUT)
OUTPUT.mkdir(parents=True)
for path in selected:
    if not allowed(path):
        raise ValueError(f'Unexpected file: {path.name}')
    dest = OUTPUT / path.relative_to(ROOT)
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(path, dest)
# The core bundle has no optional demonstrator sources and cannot activate them.
pom = OUTPUT / 'runner/pom.xml'
pom.write_text(re.sub(r'\s*<profiles>.*?</profiles>', '', pom.read_text(), flags=re.S))
package = OUTPUT / 'components/code-editor/package.json'
data = json.loads(package.read_text())
data['scripts'] = {'build': 'vite build', 'build:library': 'vite build'}
package.write_text(json.dumps(data, indent=2) + '\n')
(OUTPUT / 'components/code-editor/vite.config.js').write_text('''import { defineConfig } from "vite";
export default defineConfig({build: {
  lib: {entry: "src/execution-editor.js", formats: ["es"], fileName: "execution-editor", cssFileName: "style"},
  rollupOptions: {external: id => id === "codemirror" || id.startsWith("@codemirror/")}
}});
''')
(OUTPUT / 'README.md').write_text('''# CodeLobby — moduł wykonawczy do integracji

Zawiera serwis wykonawczy, bibliotekę edytora, Judge0 i testy.
Nie zawiera demonstracyjnej strony ani mini-backendu.

Zacznij od [przewodnika dla backendowca](docs/BACKEND-REVIEW.md),
[instrukcji integracji](docs/MAIN-REPO-INTEGRATION.md)
i [Dla BACKENDOWCA](Dla%20BACKENDOWCA.md).

Testy: `mvn -f runner/pom.xml clean test`.
Edytor: `npm --prefix components/code-editor ci` i `npm --prefix components/code-editor run build`.
Sandbox i uruchomienie serwisu: docs/team-quickstart.md — używaj
trybu bez demo, czyli `mvn spring-boot:run` bez `-Pdemo` i bez flagi demo.
Instrukcje demonstratorów w pozostałych dokumentach odnoszą się
wyłącznie do pełnego repo modułu, nie do tej paczki.
''')
files = sorted(p for p in OUTPUT.rglob('*') if p.is_file())
manifest = {'contents': 'Core source and tests; no demos, Docker images or local secrets',
            'files': {str(p.relative_to(OUTPUT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in files}}
(OUTPUT / 'HANDOFF-MANIFEST.json').write_text(json.dumps(manifest, indent=2) + '\n')
archive = OUTPUT.parent / 'codelobby-main-repo.zip'
with zipfile.ZipFile(archive, 'w', zipfile.ZIP_DEFLATED) as z:
    for p in sorted(OUTPUT.rglob('*')):
        if p.is_file():
            z.write(p, 'codelobby-execution/' + str(p.relative_to(OUTPUT)))
archive.with_suffix('.zip.sha256').write_text(hashlib.sha256(archive.read_bytes()).hexdigest()+'  '+archive.name+'\n')
print(OUTPUT)
print(archive)
